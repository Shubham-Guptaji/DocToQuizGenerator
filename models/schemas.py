"""Pydantic data schemas for validation, serialization, and structured AI outputs."""
from enum import Enum
from typing import Dict, List, Optional, Union
from pydantic import BaseModel, Field, field_validator, model_validator


class DifficultyLevel(str, Enum):
    """Supported difficulty levels for quiz generation."""
    EASY = "Easy"
    MEDIUM = "Medium"
    HARD = "Hard"
    MIXED = "Mixed"


class OptionKey(str, Enum):
    """Multiple choice options."""
    A = "A"
    B = "B"
    C = "C"
    D = "D"


class OptionsModel(BaseModel):
    """Explicit four options model ensuring Gemini Developer API compatibility without additionalProperties."""
    A: str = Field(description="Option A text")
    B: str = Field(description="Option B text")
    C: str = Field(description="Option C text")
    D: str = Field(description="Option D text")

    def __len__(self) -> int:
        return 4

    def __getitem__(self, key: str) -> str:
        if hasattr(self, key):
            return getattr(self, key)
        raise KeyError(key)

    def get(self, key: str, default=None):
        return getattr(self, key, default)

    def items(self):
        return [("A", self.A), ("B", self.B), ("C", self.C), ("D", self.D)]

    def keys(self):
        return ["A", "B", "C", "D"]

    def values(self):
        return [self.A, self.B, self.C, self.D]


class QuestionItem(BaseModel):
    """Individual generated Multiple Choice Question schema."""
    question_id: str = Field(description="Unique question identifier, e.g. Q1, Q2, etc.")
    question: str = Field(description="Clear, unambiguous question text based on the source document.")
    options: OptionsModel = Field(
        description="Exactly four options keyed by 'A', 'B', 'C', and 'D'."
    )
    correct_answer: str = Field(
        description="The single correct option key: must be 'A', 'B', 'C', or 'D'."
    )
    explanation: str = Field(
        description="Clear, educational explanation of why the correct option is right."
    )
    topic: str = Field(
        default="General",
        description="Core subject, chapter, or concept this question tests."
    )
    difficulty: str = Field(
        default="Medium",
        description="Difficulty tier: 'Easy', 'Medium', or 'Hard'."
    )
    source_reference: Optional[str] = Field(
        default=None,
        description="Reference to source page number, section heading, or excerpt."
    )

    @field_validator("correct_answer")
    @classmethod
    def validate_correct_answer(cls, v: str) -> str:
        clean = v.strip().upper()
        if clean not in {"A", "B", "C", "D"}:
            raise ValueError(f"correct_answer must be A, B, C, or D; got '{v}'")
        return clean

    @model_validator(mode="after")
    def validate_options_keys(self) -> "QuestionItem":
        expected = {"A", "B", "C", "D"}
        actual = set(self.options.keys())
        if actual != expected:
            raise ValueError(f"Options keys must be exactly ['A', 'B', 'C', 'D']; got {sorted(actual)}")
        for key in expected:
            if not str(self.options[key]).strip():
                raise ValueError(f"Option {key} content cannot be blank.")
        return self


class QuizQuestionsResponse(BaseModel):
    """Structured response container for multiple questions generated by Gemini."""
    questions: List[QuestionItem] = Field(
        description="List of validated multiple-choice questions extracted from the document."
    )


class DocumentMetadata(BaseModel):
    """Metadata extracted from an uploaded PDF document."""
    document_id: Optional[str] = None
    filename: str
    file_size_bytes: int
    page_count: int
    char_count: int
    word_count: int
    extracted_text_preview: str
    is_scanned_ocr_needed: bool = False
    created_at: Optional[str] = None


class QuizConfig(BaseModel):
    """User configuration for generating a quiz."""
    document_id: Optional[str] = None
    question_count: int = Field(default=50, ge=1, le=100)
    difficulty: DifficultyLevel = DifficultyLevel.MEDIUM
    topic_focus: Optional[str] = None
    language: str = Field(default="English")
    time_limit_minutes: Optional[int] = Field(default=None, ge=1, le=300)


class QuizSubmission(BaseModel):
    """User submission containing selected answers."""
    quiz_id: str
    time_taken_seconds: int = Field(default=0, ge=0)
    answers: Dict[str, str] = Field(
        default_factory=dict,
        description="Mapping from question_id to selected option ('A', 'B', 'C', 'D') or empty if unanswered."
    )


class QuestionReviewItem(BaseModel):
    """Item for detailed answer review post-submission."""
    question_id: str
    question: str
    options: Union[Dict[str, str], OptionsModel]
    selected_answer: Optional[str] = None
    correct_answer: str
    is_correct: bool
    is_unanswered: bool
    explanation: str
    mistake_analysis: Optional[str] = None
    topic: str
    difficulty: str
    source_reference: Optional[str] = None


class TopicPerformance(BaseModel):
    """Performance breakdown for a single topic."""
    topic: str
    total_questions: int
    correct_count: int
    accuracy_percentage: float


class QuizResult(BaseModel):
    """Deterministic calculated score and outcome of a quiz attempt."""
    attempt_id: Optional[str] = None
    quiz_id: str
    total_questions: int
    correct_count: int
    incorrect_count: int
    unanswered_count: int
    score_percentage: float
    accuracy_rate: float
    time_taken_seconds: int
    time_taken_formatted: str
    performance_grade: str
    summary_message: str
    topic_breakdowns: List[TopicPerformance]
    reviews: List[QuestionReviewItem]


class AIFeedback(BaseModel):
    """AI-generated educational feedback and personalized improvement plan."""
    overall_assessment: str = Field(
        description="Comprehensive summary of how well the student understood the material."
    )
    strongest_topics: List[str] = Field(
        description="Topics or concepts where the student demonstrated solid mastery."
    )
    weak_topics: List[str] = Field(
        description="Topics or concepts requiring targeted review and reinforcement."
    )
    common_mistakes: List[str] = Field(
        description="Analysis of misconceptions and typical error patterns identified in wrong answers."
    )
    prioritized_revision_plan: List[str] = Field(
        description="Actionable, prioritized step-by-step revision checklist."
    )
    suggested_follow_up_activities: List[str] = Field(
        description="Specific recommended exercises, conceptual deep dives, or practice problems."
    )
    encouragement: str = Field(
        description="Motivating and constructive closing remarks grounded in actual performance."
    )
